import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { GearItem, WeightUnit } from '@/lib/data';
import { convertWeight, calcStats, CATEGORY_ORDER } from '@/lib/data';

export function downloadCSV(gear: GearItem[], unit: WeightUnit, listName: string) {
  const date = new Date().toISOString().split('T')[0];
  const stats = calcStats(gear);
  let csv = `Item Name,Category,Type,Quantity,Weight (${unit}),Price ($)\n`;
  gear.forEach(g => {
    csv += `"${g.name}","${g.category}","${g.type}",${g.qty},${convertWeight(g.weight * g.qty, unit)},${(g.price * g.qty).toFixed(2)}\n`;
  });
  csv += `\nTotals,,,${stats.totalItems},${convertWeight(stats.totalWeight, unit)},${stats.totalCost.toFixed(2)}\n`;
  const blob = new Blob([csv], { type: 'text/csv' });
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = `TrailPack-${listName.replace(/\s+/g, '-')}-${date}.csv`;
  a.click();
  URL.revokeObjectURL(a.href);
}

export function downloadPDF(gear: GearItem[], unit: WeightUnit, listName: string, userName?: string, trailName?: string) {
  const doc = new jsPDF();
  const stats = calcStats(gear);
  const date = new Date().toLocaleDateString();

  // Header bar
  doc.setFillColor(15, 25, 35);
  doc.rect(0, 0, 210, 38, 'F');
  doc.setTextColor(240, 236, 228);
  doc.setFontSize(20);
  doc.text('TrailPack', 15, 18);
  doc.setFontSize(10);
  doc.text(listName, 15, 28);
  if (userName) doc.text(`By ${userName}`, 100, 28);
  doc.text(date, 195, 28, { align: 'right' });

  // Stats row
  let y = 48;
  doc.setTextColor(60, 60, 60);
  doc.setFontSize(8);
  const parts = [
    `Base Weight: ${convertWeight(stats.baseWeight, unit)} ${unit}`,
    `Total: ${convertWeight(stats.totalWeight, unit)} ${unit}`,
    `Items: ${stats.totalItems}`,
    `Cost: $${stats.totalCost.toFixed(2)}`,
  ];
  if (trailName) parts.unshift(`Trail: ${trailName}`);
  doc.text(parts.join('   |   '), 15, y);
  y += 10;

  // Gear tables by category
  CATEGORY_ORDER.forEach(cat => {
    const catGear = gear.filter(g => g.category === cat);
    if (catGear.length === 0) return;

    if (y > 260) { doc.addPage(); y = 20; }

    doc.setFillColor(74, 124, 89);
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(9);
    doc.rect(14, y - 4, 182, 7, 'F');
    doc.text(cat, 16, y + 1);
    y += 8;

    autoTable(doc, {
      startY: y,
      head: [['\u2610', 'Item', 'Type', 'Qty', `Wt (${unit})`, 'Price']],
      body: catGear.map(g => [
        '\u2610', g.name, g.type, String(g.qty),
        convertWeight(g.weight * g.qty, unit), `$${(g.price * g.qty).toFixed(2)}`
      ]),
      theme: 'grid',
      headStyles: { fillColor: [26, 35, 50], textColor: [240, 236, 228], fontSize: 7 },
      bodyStyles: { fontSize: 7, cellPadding: 2 },
      columnStyles: { 0: { cellWidth: 8 } },
      margin: { left: 14, right: 14 },
    });
    y = (doc as any).lastAutoTable.finalY + 6;
  });

  // Footer
  doc.setFontSize(6);
  doc.setTextColor(139, 157, 175);
  doc.text('Generated by TrailPack', 105, 290, { align: 'center' });

  doc.save(`TrailPack-${listName.replace(/\s+/g, '-')}-${new Date().toISOString().split('T')[0]}.pdf`);
}
