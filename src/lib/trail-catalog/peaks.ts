/** Convert peak definition into a full CatalogTrail record. */
export function peakToCatalogTrail(p: PeakDefinition): CatalogTrail {
  return {
    id: p.id,
    name: `${p.name} (${p.summitElevationFt.toLocaleString("en-US")} ft)`,
    country: p.country,
    region: p.region,
    kind: "route",
    miles: p.roundTripMiles,
    distanceBasis: "source",
    latitude: p.latitude,
    longitude: p.longitude,
    difficulty: computeDifficulty({ lengthMi: p.roundTripMiles, gainFt: p.elevationGainFt, maxElevFt: p.summitElevationFt }),
    reportedDifficulty: p.difficultyClass,
    gainFt: p.elevationGainFt,
    maxElevFt: p.summitElevationFt,
    dogs: p.category === "14er" ? true : false,
    source: "peak",
    sourceId: p.id,
    sourceUrl: `https://en.wikipedia.org/wiki/${encodeURIComponent(p.name.split("(")[0].trim())}`,
    officialUrl: `https://www.google.com/maps/search/?api=1&query=${p.latitude},${p.longitude}`,
    sourceDate: "2026-10-21",
    manager: p.range,
    surface: "rock / snow / trail",
    season: p.season,
    geometryShard: "route",
    sectionCount: 1,
    mappedMiles: p.roundTripMiles,
    peakCategory: p.category,
    summitElevationFt: p.summitElevationFt,
    summitElevationM: p.summitElevationM,
    routeType: "point-to-point",
    tags: p.tags,
    note: `${p.description} Standard route: ${p.standardRoute}. Elevation gain: +${p.elevationGainFt.toLocaleString("en-US")} ft. Summit elevation: ${p.summitElevationFt.toLocaleString("en-US")} ft (${p.summitElevationM.toLocaleString("en-US")} m).`,
    elevationFt: {
      min: Math.max(0, p.summitElevationFt - p.elevationGainFt),
      max: p.summitElevationFt,
    },
  };
}

/** Generate realistic approach and ascent coordinates from trailhead to summit. */
/** Return all summit records formatted as CatalogTrails. */
export function getAllPeakTrails(): CatalogTrail[] {
  return PEAK_DEFINITIONS.map(peakToCatalogTrail);
}
